/** Writes src/lock-duas.ts: the Quranic du'as whose whole text fits the Lock Screen rectangle, measured with the widget's
 * font and SwiftUI layout on a box smaller than any iPhone's rectangle (the phone draws Arabic a little taller than the
 * Mac does: 2:250 fitted 158×66 here and still fell back on an iPhone 16 Pro). Requires macOS with swiftc; run after
 * `npm run build` and again whenever the du'a list, the corpus or the widget font changes:
 *   node scripts/measure-lock-duas.mjs */
import { writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { QURANIC_DUAS } from '../www/js/duas.js';
import { chapter, verse } from '../www/js/data.js';
import { duaKey, duaTextHash } from '../www/js/smart.js';

export const BOX = { width: 145, height: 56 };
const dir = mkdtempSync(join(tmpdir(), 'ayahflow-measure-'));
const duas = QURANIC_DUAS.map(([s, a, b]) => ({ ref: duaKey([s, a, b]), name: chapter(s).name, text: Array.from({ length: b - a + 1 }, (_, k) => verse(s, a + k)).join(' ') }));
writeFileSync(join(dir, 'duas.json'), JSON.stringify(duas));
const bin = join(dir, 'measure');
let r = spawnSync('swiftc', ['-O', 'scripts/measure-lock-duas.swift', '-o', bin], { stdio: 'inherit' });
if (r.status !== 0) process.exit(r.status ?? 1);
r = spawnSync(bin, ['ios/App/AyahFlowWidget/AyahFlowQuran-Regular.ttf', join(dir, 'duas.json'), String(BOX.width), String(BOX.height)], { encoding: 'utf8' });
if (r.status !== 0) { console.error(r.stderr); process.exit(r.status ?? 1); }
const fit = r.stdout.split('\n').filter(Boolean);
writeFileSync('src/lock-duas.ts', `/** Generated by scripts/measure-lock-duas.mjs (${BOX.width}×${BOX.height} pt, AyahFlowQuran-Regular.ttf): the du'as shown whole on the
 * Lock Screen rectangle, ${fit.length} of ${duas.length}. LOCK_DUAS_HASH is duaTextHash of their text; tests fail if it no longer matches. */
export const LOCK_DUAS: readonly string[] = ${JSON.stringify(fit)};
export const LOCK_DUAS_HASH = '${duaTextHash(fit)}';
`);
console.log(`${fit.length}/${duas.length} du'as fit ${BOX.width}×${BOX.height}; wrote src/lock-duas.ts`);
