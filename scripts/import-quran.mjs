/** Reproducible import of the full Quran text from the committed, verbatim Tanzil files.
 * Source: Tanzil Quran Text (Uthmani, Version 1.1), CC BY 3.0, https://tanzil.net — verbatim only, no changes.
 * The ayah strings are copied exactly as published (the XML entity layer is the only thing decoded).
 * The basmala is Tanzil's separate `bismillah` attribute; it is never merged into an ayah.
 * Checksums are pinned: a changed file fails the build until the new version is reviewed and the pin updated.
 * Usage: node scripts/import-quran.mjs [outfile]   (build.mjs calls importQuran()). */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const QURAN_FILES = {
    text: { path: 'content/tanzil/quran-uthmani.xml', sha256: 'c5052534d63d3856ce25413ff464d0b609f90169a202a1615aa8707efec81244', url: 'https://tanzil.net/pub/download/index.php?marks=true&sajdah=true&rub=true&tatweel=true&quranType=uthmani&outType=xml&agree=true' },
    meta: { path: 'content/tanzil/quran-data.xml', sha256: '8867c1d88191472adec9db694b3cd9f135b1a2ef580574d32cf888dcb22c5c7a', url: 'https://tanzil.net/res/text/metadata/quran-data.xml' },
};
const entities = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'" };
const decode = (s) => s.replace(/&(amp|lt|gt|quot|apos);/g, (_, e) => entities[e]);
const attrs = (tag) => Object.fromEntries([...tag.matchAll(/(\w+)="([^"]*)"/g)].map(m => [m[1], decode(m[2])]));
async function verified(file) {
    const buf = await readFile(path.join(root, file.path));
    const hash = createHash('sha256').update(buf).digest('hex');
    if (hash !== file.sha256) throw new Error(`${file.path}: sha256 ${hash} != pinned ${file.sha256}. Review the Tanzil update before changing the pin.`);
    return buf.toString('utf8');
}
export async function importQuran() {
    const [xml, metaXml] = await Promise.all([verified(QURAN_FILES.text), verified(QURAN_FILES.meta)]);
    const notice = xml.match(/<!--([\s\S]*?)-->/)[1].trim();
    const meta = [...metaXml.matchAll(/<sura [^>]*\/>/g)].map(m => attrs(m[0]));
    const juz = [...metaXml.matchAll(/<juz [^>]*\/>/g)].map(m => { const a = attrs(m[0]); return [Number(a.sura), Number(a.aya)]; });
    const ruku = [...metaXml.matchAll(/<ruku [^>]*\/>/g)].map(m => { const a = attrs(m[0]); return [Number(a.sura), Number(a.aya)]; });
    // First ayah of each of the 604 pages of the Madani Mushaf, as Tanzil's metadata records them (boundaries only).
    const pages = [...metaXml.matchAll(/<page [^>]*\/>/g)].map((m, i) => { const a = attrs(m[0]); if (Number(a.index) !== i + 1) throw new Error(`Page order mismatch at ${i + 1}`); return [Number(a.sura), Number(a.aya)]; });
    const blocks = [...xml.matchAll(/<sura ([^>]*)>([\s\S]*?)<\/sura>/g)];
    if (blocks.length !== 114 || meta.length !== 114 || juz.length !== 30 || ruku.length !== 556 || pages.length !== 604) throw new Error('Unexpected Tanzil structure');
    let global = 0;
    const surahs = blocks.map((b, i) => {
        const head = attrs(b[1]), m = meta[i], id = Number(head.index);
        if (id !== i + 1 || Number(m.index) !== id) throw new Error(`Sura order mismatch at ${i + 1}`);
        const ayahs = [...b[2].matchAll(/<aya [^>]*\/>/g)].map(a => attrs(a[0]));
        if (ayahs.length !== Number(m.ayas) || Number(m.start) !== global) throw new Error(`Sura ${id}: ayah count or start mismatch`);
        ayahs.forEach((a, k) => { if (Number(a.index) !== k + 1 || !a.text) throw new Error(`Sura ${id}: bad ayah ${k + 1}`); });
        global += ayahs.length;
        return { id, ar: head.name, name: m.tname, en: m.ename, type: m.type === 'Medinan' ? 'medinan' : 'meccan', bismillah: ayahs[0].bismillah ?? null, verses: ayahs.map(a => a.text) };
    });
    if (global !== 6236) throw new Error(`Expected 6236 ayahs, got ${global}`);
    return { source: 'Tanzil Quran Text (Uthmani, Version 1.1)', licence: 'CC BY 3.0', url: 'https://tanzil.net', sha256: QURAN_FILES.text.sha256, notice, juz, ruku, pages, surahs };
}
export async function writeQuranModule(outfile) {
    const q = await importQuran();
    await writeFile(outfile, `/* Generated by scripts/import-quran.mjs from content/tanzil/ — do not edit.\n${q.notice.replace(/\*\//g, '* /')}\n*/\nexport default ${JSON.stringify(q)};\n`);
    return q;
}
if (import.meta.url === `file://${process.argv[1]}`) {
    const q = await writeQuranModule(process.argv[2] ?? path.join(root, 'www/js/quran-data.js'));
    console.log(`Imported ${q.surahs.length} surahs, ${q.surahs.reduce((n, s) => n + s.verses.length, 0)} ayahs from ${q.source}.`);
}
