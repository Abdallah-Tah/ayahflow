/** Reproducible import of the English translation shown under ayahs: Pickthall (1930), as published by Tanzil
 * (https://tanzil.net/trans/, file en.pickthall, "Last Update: September 4, 2010"). Lines are copied exactly; only the
 * "surah|ayah|" prefix is removed. The checksum is pinned: a changed file fails the build until it is reviewed.
 * Tanzil states its translation files are "for non-commercial purposes only"; the translation itself is in the public
 * domain (published 1930, translator died 1936). See docs/CONTENT-PROVENANCE.md before any paid release. */
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const TRANSLATION_FILE = { path: 'content/translations/en.pickthall.txt', sha256: '4aabbfa9d96796f5a6b0217d2c39dce1a3084f772bf6f2650e37082a774e3cc7', url: 'https://tanzil.net/trans/?transID=en.pickthall&type=txt-2' };
export async function importTranslation() {
    const buf = await readFile(path.join(root, TRANSLATION_FILE.path));
    const hash = createHash('sha256').update(buf).digest('hex');
    if (hash !== TRANSLATION_FILE.sha256) throw new Error(`${TRANSLATION_FILE.path}: sha256 ${hash} != pinned ${TRANSLATION_FILE.sha256}`);
    const lines = buf.toString('utf8').split('\n').filter(l => l && !l.startsWith('#'));
    if (lines.length !== 6236) throw new Error(`Expected 6236 lines, got ${lines.length}`);
    const { importQuran } = await import('./import-quran.mjs');
    const quran = await importQuran();
    const surahs = quran.surahs.map(s => []);
    for (const line of lines) {
        const m = /^(\d+)\|(\d+)\|(.+)$/.exec(line);
        if (!m) throw new Error(`Bad line: ${line.slice(0, 40)}`);
        const s = Number(m[1]), a = Number(m[2]);
        if (s < 1 || s > 114 || a !== surahs[s - 1].length + 1) throw new Error(`Out of order: ${s}:${a}`);
        surahs[s - 1].push(m[3]);
    }
    quran.surahs.forEach((s, i) => { if (surahs[i].length !== s.verses.length) throw new Error(`Surah ${s.id}: ${surahs[i].length} lines for ${s.verses.length} ayahs`); });
    return { id: 'en.pickthall', name: 'Pickthall', translator: 'Mohammed Marmaduke William Pickthall', source: 'Tanzil.net', url: 'https://tanzil.net/trans/', sha256: hash, surahs };
}
export async function writeTranslationModule(outfile) {
    const t = await importTranslation();
    await writeFile(outfile, `/* Generated by scripts/import-translation.mjs from ${TRANSLATION_FILE.path} — do not edit. Pickthall (1930), via Tanzil.net. */\nexport default ${JSON.stringify(t)};\n`);
    return t;
}
